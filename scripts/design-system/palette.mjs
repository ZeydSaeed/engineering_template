function fail(message) {
    console.error(`palette: ${message}`);
    process.exit(1);
}

function readJson(path) {
    try {
        return JSON.parse(readFileSync(resolve(ROOT, path), 'utf8'));
    } catch (error) {
        return fail(`${path}: ${error.message}`);
    }
}

const HEX = /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i;

function readPalette() {
    const config = readJson(PATHS.palette);

    if (config.version !== 1) {
        fail(`${PATHS.palette}: "version" must be 1.`);
    }

    const supplied = { ...config.colors, ...config.extra };

    if (!supplied.primary?.hex) {
        fail(`${PATHS.palette}: colors.primary.hex is required.`);
    }

    for (const [key, entry] of Object.entries(supplied)) {
        if (!/^[a-z][a-z0-9]*$/.test(key)) {
            fail(
                `${PATHS.palette}: family name "${key}" must be lower-case letters and digits.`,
            );
        }

        if (
            entry?.hex !== null &&
            entry?.hex !== undefined &&
            !HEX.test(entry.hex)
        ) {
            fail(
                `${PATHS.palette}: ${key}.hex "${entry.hex}" is not #RGB or #RRGGBB.`,
            );
        }
    }

    return config;
}

// ---------------------------------------------------------- L3 tokens (§7)

function parseBlock(text, selector) {
    const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const block = text.match(
        new RegExp(`^${escaped} \\{([\\s\\S]*?)^\\}`, 'm'),
    );
    const tokens = {};

    for (const [, name, value] of (block?.[1] ?? '').matchAll(
        /--([a-z0-9-]+):\s*([^;]+);/g,
    )) {
        tokens[name] = value.trim();
    }

    return tokens;
}

// ------------------------------------------------------------ L2 roles (§6)

// A reference is "family-step", { mix: [ref, percent, ref] } or
// { alpha: [ref, percent] }.
function makeResolver(families) {
    const lookup = (ref) => {
        const match = /^([a-z][a-z0-9]*)-(\d+)$/.exec(ref);
        const family = match && families[match[1]];
        const step = match && Number(match[2]);

        if (family && step === 0 && match[1] === 'neutral') {
            return { l: 1, c: 0, h: 0, alpha: 1 };
        }

        if (family && step === 1000 && match[1] === 'neutral') {
            return { l: 0, c: 0, h: 0, alpha: 1 };
        }

        if (!family || !family.steps[step]) {
            throw new Error(
                `unknown palette reference "${JSON.stringify(ref)}"`,
            );
        }

        return family.steps[step];
    };

    const value = (ref) => {
        if (typeof ref === 'string') {
            return lookup(ref);
        }

        if (ref?.mix) {
            return normalise(
                mix(lookup(ref.mix[0]), ref.mix[1], lookup(ref.mix[2])),
            );
        }

        if (ref?.alpha) {
            return mix(lookup(ref.alpha[0]), ref.alpha[1], 'transparent');
        }

        throw new Error(`invalid reference ${JSON.stringify(ref)}`);
    };

    const toCss = (ref) => {
        if (typeof ref === 'string') {
            return `var(--palette-${ref})`;
        }

        if (ref.mix) {
            return `color-mix(in oklch, var(--palette-${ref.mix[0]}) ${ref.mix[1]}%, var(--palette-${ref.mix[2]}))`;
        }

        return `color-mix(in oklch, var(--palette-${ref.alpha[0]}) ${ref.alpha[1]}%, transparent)`;
    };

    return { value, toCss };
}

