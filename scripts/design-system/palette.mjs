// ---------------------------------------------------------------- colour maths

const round = (value, places) => Number(value.toFixed(places));

function hexToOklch(hex) {
    const full =
        hex.length === 4
            ? `#${hex[1]}${hex[1]}${hex[2]}${hex[2]}${hex[3]}${hex[3]}`
            : hex;
    const rgb = [1, 3, 5].map((i) => parseInt(full.slice(i, i + 2), 16) / 255);
    const [r, g, b] = rgb.map((c) =>
        c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4,
    );
    const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
    const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
    const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
    const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
    const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
    const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
    const C = Math.hypot(A, B);
    const H = C < 1e-4 ? 0 : ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360;

    return { l: L, c: C, h: H };
}

function oklchToLinear({ l, c, h }) {
    const rad = (h * Math.PI) / 180;
    const a = c * Math.cos(rad);
    const b = c * Math.sin(rad);
    const L = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
    const M = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
    const S = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;

    return [
        4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S,
        -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S,
        -0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S,
    ];
}

const inGamut = (colour) =>
    oklchToLinear(colour).every((v) => v >= -1e-4 && v <= 1 + 1e-4);

// §5.2: reduce chroma at constant lightness and hue until it fits sRGB.
function gamutMap(colour) {
    if (inGamut(colour)) {
        return { colour, reduced: 0 };
    }

    let low = 0;
    let high = colour.c;

    while (high - low > 0.001) {
        const mid = (low + high) / 2;

        if (inGamut({ ...colour, c: mid })) {
            low = mid;
        } else {
            high = mid;
        }
    }

    return { colour: { ...colour, c: low }, reduced: colour.c - low };
}

// The CSS form: L and C to 3 places, H to 1, like the hand-written tokens.
const normalise = ({ l, c, h, alpha = 1 }) => ({
    l: round(l, 3),
    c: round(c, 3),
    h: round(c < 0.0005 ? 0 : h, 1),
    alpha,
});
const css = ({ l, c, h }) => `oklch(${l} ${c} ${h})`;

const encode = (v) => {
    const c = Math.min(1, Math.max(0, v));

    return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
};
const decode = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);

// Gamma-encoded sRGB, composited over an opaque surface when translucent.
function srgb(colour, over) {
    const top = oklchToLinear(colour).map(encode);

    if ((colour.alpha ?? 1) >= 1 || !over) {
        return top;
    }

    const bottom = srgb(over);

    return top.map((v, i) => v * colour.alpha + bottom[i] * (1 - colour.alpha));
}

function luminance(colour, over) {
    const [r, g, b] = srgb(colour, over).map(decode);

    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(one, two, over) {
    const a = luminance(one, over);
    const b = luminance(two, over);

    return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

// color-mix(in oklch, A p%, B): L, C and alpha linear, hue along the shorter
// arc; an achromatic side takes the other side's hue (CSS Color 4).
function mix(a, p, b) {
    if (b === 'transparent') {
        return { ...a, alpha: p / 100 };
    }

    const t = 1 - p / 100;
    let ha = a.h;
    let hb = b.h;

    if (a.c < 0.0005) {
        ha = hb;
    }

    if (b.c < 0.0005) {
        hb = ha;
    }

    let delta = hb - ha;

    if (delta > 180) {
        delta -= 360;
    } else if (delta < -180) {
        delta += 360;
    }

    return {
        l: a.l + (b.l - a.l) * t,
        c: a.c + (b.c - a.c) * t,
        h: (ha + delta * t + 360) % 360,
        alpha: 1,
    };
}

// ---------------------------------------------------------- analysis (§4)

// Upper bounds of OKLCH hue ranges (sRGB primaries: red ~29, yellow ~110,
// green ~142, cyan ~195, blue ~264, magenta ~328).
const HUE_FAMILIES = [
    [40, 'red'],
    [75, 'orange'],
    [115, 'yellow'],
    [165, 'green'],
    [215, 'teal'],
    [275, 'blue'],
    [320, 'purple'],
    [350, 'pink'],
    [360, 'red'],
];

function classify({ l, c, h }) {
    return {
        lightness: l < 0.4 ? 'dark' : l > 0.75 ? 'light' : 'mid',
        chroma: c < 0.03 ? 'neutral' : c < 0.08 ? 'muted' : 'vivid',
        hue: c < 0.03 ? 'grey' : HUE_FAMILIES.find(([max]) => h < max)[1],
        temperature: h < 110 || h >= 330 ? 'warm' : 'cool',
    };
}

const hueDistance = (a, b) => {
    const d = Math.abs(a - b) % 360;

    return d > 180 ? 360 - d : d;
};

const deltaE = (a, b) => {
    const [x, y] = [a, b].map(({ l, c, h }) => [
        l,
        c * Math.cos((h * Math.PI) / 180),
        c * Math.sin((h * Math.PI) / 180),
    ]);

    return Math.hypot(x[0] - y[0], x[1] - y[1], x[2] - y[2]);
};

// ------------------------------------------------------------ L1 scales (§5)

function chromaFactor(l, anchorL) {
    if (l >= anchorL) {
        const t = anchorL >= 0.98 ? 1 : (l - anchorL) / (0.98 - anchorL);

        return 1 - 0.65 * Math.min(1, Math.max(0, t));
    }

    const t = anchorL <= 0.2 ? 1 : (anchorL - l) / (anchorL - 0.2);

    return 1 - 0.4 * Math.min(1, Math.max(0, t));
}

function buildFamily(name, base, exact, flags, constantChroma = false) {
    const anchor = STEPS.reduce((best, step) =>
        Math.abs(TARGET_L[step] - base.l) < Math.abs(TARGET_L[best] - base.l)
            ? step
            : best,
    );
    const steps = {};

    for (const step of STEPS) {
        if (exact && step === anchor) {
            steps[step] = normalise(base);
            continue;
        }

        const chroma = constantChroma
            ? base.c
            : base.c * chromaFactor(TARGET_L[step], base.l);
        const { colour, reduced } = gamutMap({
            l: TARGET_L[step],
            c: chroma,
            h: base.h,
        });

        if (reduced > 0.02) {
            flags.push(
                `${name}-${step}: chroma reduced by ${reduced.toFixed(3)} to fit sRGB.`,
            );
        }

        steps[step] = normalise(colour);
    }

    return {
        name,
        base: normalise(base),
        anchor: exact ? anchor : null,
        steps,
    };
}

