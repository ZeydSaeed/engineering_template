export const ROLE_NAMES = DEFAULTS.light.map(([name]) => name);

function mapTheme(theme, families, overrides, problems) {
    const resolver = makeResolver(families);
    const refs = {};
    const values = {};
    const notes = {};
    const isDark = theme === 'dark';

    const passes = (colour, { text = [], boundary = [], carries = false }) =>
        text.every((role) => contrast(colour, values[role]) >= 4.5) &&
        boundary.every((role) => contrast(colour, values[role]) >= 3) &&
        (!carries || foregroundFor(colour, null) !== null);

    // §6.2: the family's lightest step, white, the family's darkest step,
    // black: the first with 4.5:1.
    const foregroundFor = (colour, family) => {
        const candidates = family
            ? [`${family}-50`, 'neutral-0', `${family}-950`, 'neutral-1000']
            : ['neutral-0', 'neutral-1000'];

        return (
            candidates.find(
                (ref) => contrast(resolver.value(ref), colour) >= 4.5,
            ) ?? null
        );
    };

    const pick = (spec) => {
        const family = families[spec.pick];
        const start =
            spec.from === 'anchor' ? (family.anchor ?? 500) : spec.from;
        const index = STEPS.indexOf(start);
        // Outward from the start; ties go darker in light, lighter in dark.
        const order = [start];

        for (let d = 1; d < STEPS.length; d += 1) {
            const towardDark = STEPS[index + d];
            const towardLight = STEPS[index - d];
            const first = isDark ? towardLight : towardDark;
            const second = isDark ? towardDark : towardLight;

            for (const step of [first, second]) {
                if (step !== undefined) {
                    order.push(step);
                }
            }
        }

        const found = order.find((step) => passes(family.steps[step], spec));

        if (found === undefined) {
            return null;
        }

        if (found !== start) {
            notes[spec.role] =
                `${spec.pick}-${start} did not meet its contrast requirements; ${spec.pick}-${found} is used.`;
        }

        return `${spec.pick}-${found}`;
    };

    // §6.5: project roles are extra keys in palette.json "roles", after the
    // canonical ones; a project "-foreground" may be "auto".
    const projectRoles = Object.keys(overrides ?? {})
        .filter((role) => !ROLE_NAMES.includes(role))
        .map((role) => [role, undefined]);

    for (const [role, fallback] of [...DEFAULTS[theme], ...projectRoles]) {
        const given = overrides?.[role];
        const spec = given ?? fallback;
        let ref = null;

        try {
            if (spec === undefined) {
                throw new Error(
                    'a project role needs a value in palette.json "roles"',
                );
            } else if (spec === 'auto') {
                const base = role.replace(/-foreground$/, '');

                ref = foregroundFor(values[base], familyOf(refs[base]));
            } else if (typeof spec === 'string' || spec.mix || spec.alpha) {
                ref = spec;
                resolver.value(ref);
            } else if (spec.pick) {
                ref = pick({ ...spec, role });
            } else if (spec.shift) {
                const baseRef = refs[spec.shift];
                const base = familyOf(baseRef);
                const step = stepOf(baseRef);
                // Away from the foreground: a light text gets a darker hover.
                const fg = values[`${spec.shift}-foreground`];
                const direction = fg && fg.l > values[spec.shift].l ? 1 : -1;
                const index = Math.min(
                    STEPS.length - 1,
                    Math.max(0, STEPS.indexOf(step) + direction * spec.by),
                );

                ref = Number.isNaN(step) ? baseRef : `${base}-${STEPS[index]}`;
            }
        } catch (error) {
            problems.push(`${theme} ${role}: ${error.message}`);
        }

        if (ref === null) {
            problems.push(
                `${theme} ${role}: no step of the palette meets the contrast it needs; set it in palette.json "roles".`,
            );
            continue;
        }

        refs[role] = ref;
        values[role] = resolver.value(ref);

        if (given !== undefined) {
            notes[role] = 'Set in palette.json "roles".';
        }
    }

    return { refs, values, notes, resolver };
}

// ------------------------------------------------------------ gradients (§9)

function buildGradients(config, families, themes, problems) {
    const gradients = {};

    for (const gradient of config.gradients ?? []) {
        const { name, angle = 90, stops = [], foreground } = gradient;

        if (!/^[a-z][a-z0-9-]*$/.test(name ?? '')) {
            problems.push(`gradient "${name}": invalid name.`);
            continue;
        }

        if (stops.length < 2 || stops.length > 3) {
            problems.push(`gradient ${name}: needs 2 or 3 stops.`);
            continue;
        }

        for (const theme of gradient.themes ?? Object.keys(THEME_SELECTORS)) {
            const { resolver, values } = themes[theme];
            let colours;

            try {
                colours = stops.map((ref) => resolver.value(ref));
            } catch (error) {
                problems.push(`gradient ${name}: ${error.message}`);
                continue;
            }

            const text = values[foreground];

            if (!text) {
                problems.push(
                    `gradient ${name}: unknown foreground role "${foreground}".`,
                );
                continue;
            }

            const weakest = Math.min(...colours.map((c) => contrast(text, c)));
            const jump = Math.max(
                ...colours.slice(1).map((c, i) => Math.abs(c.l - colours[i].l)),
            );

            if (weakest < 4.5) {
                problems.push(
                    `${theme} gradient ${name}: ${foreground} reaches only ${weakest.toFixed(2)}:1 on a stop (4.5 needed).`,
                );
                continue;
            }

            if (jump > 0.15) {
                problems.push(
                    `${theme} gradient ${name}: adjacent stops differ by ${jump.toFixed(2)} in lightness (0.15 allowed).`,
                );
                continue;
            }

            gradients[theme] ??= {};
            gradients[theme][name] = {
                css: `linear-gradient(${angle}deg, ${stops.map((ref) => resolver.toCss(ref)).join(', ')})`,
                weakest,
                foreground,
            };
        }
    }

    return gradients;
}

// ---------------------------------------------------------------- pairs

function tokenValues(themeValues, components) {
    const all = { ...themeValues };
    const resolveVar = (expression, depth = 0) => {
        if (depth > 10) {
            throw new Error(`reference loop in ${expression}`);
        }

        const plain = /^var\(--([a-z0-9-]+)\)$/.exec(expression);

        if (plain) {
            const name = plain[1];

            if (all[name]) {
                return all[name];
            }

            if (components[name]) {
                return resolveVar(components[name], depth + 1);
            }

            throw new Error(`unknown token --${name}`);
        }

        const mixed =
            /^color-mix\(in oklch, (var\(--[a-z0-9-]+\)) (\d+)%, (transparent|var\(--[a-z0-9-]+\))\)$/.exec(
                expression,
            );

        if (mixed) {
            const right =
                mixed[3] === 'transparent'
                    ? 'transparent'
                    : resolveVar(mixed[3], depth + 1);

            return mix(
                resolveVar(mixed[1], depth + 1),
                Number(mixed[2]),
                right,
            );
        }

        throw new Error(`cannot evaluate ${expression}`);
    };

    for (const name of Object.keys(components)) {
        all[name] = resolveVar(components[name]);
    }

    return all;
}

function checkPairs(pairs, values) {
    return pairs.map((pair) => {
        const over = pair.over ? values[pair.over] : undefined;
        const ratio = contrast(
            values[pair.fg],
            values[pair.bg],
            over ?? values.background,
        );

        return { ...pair, ratio, ok: ratio >= pair.min };
    });
}

// ---------------------------------------------------------------- output

function paletteCss(families) {
    const lines = [`/* ${HEADER} */`, '', ':root {'];

    lines.push('    --palette-neutral-0: oklch(1 0 0);');
    lines.push('    --palette-neutral-1000: oklch(0 0 0);');

    for (const family of Object.values(families)) {
        const label = family.label ? ` ${family.label}` : '';

        lines.push(`    /* ${family.name}${label}: ${family.source} */`);
        lines.push(`    --palette-${family.name}-base: ${css(family.base)};`);

        for (const step of STEPS) {
            lines.push(
                `    --palette-${family.name}-${step}: ${css(family.steps[step])};`,
            );
        }
    }

    lines.push('}', '');

    return lines.join('\n');
}

// The page background before the stylesheet arrives (app.blade.php includes
// it), so a palette change needs no hand edit there either.
function prepaintView(themes) {
    const value = (theme) => css(themes[theme].values.background);

    return [
        `{{-- ${HEADER} --}}`,
        '<style>',
        '    html {',
        `        background-color: ${value('light')};`,
        '    }',
        '',
        '    html.dark {',
        `        background-color: ${value('dark')};`,
        '    }',
        '</style>',
        '',
    ].join('\n');
}

function themesCss(themes, gradients) {
    const lines = [`/* ${HEADER} */`];

    for (const [theme, selector] of Object.entries(THEME_SELECTORS)) {
        lines.push('', `${selector} {`);

        for (const [role, ref] of Object.entries(themes[theme].refs)) {
            lines.push(`    --${role}: ${themes[theme].resolver.toCss(ref)};`);
        }

        // A gradient a theme does not list is `none` there, so it is not
        // inherited from :root on the same element.
        const names = new Set(
            Object.values(gradients).flatMap((byName) => Object.keys(byName)),
        );

        for (const name of names) {
            lines.push(
                `    --gradient-${name}: ${gradients[theme]?.[name]?.css ?? 'none'};`,
            );
        }

        lines.push('}');
    }

    const names = new Set(
        Object.values(gradients).flatMap((byName) => Object.keys(byName)),
    );

    for (const name of names) {
        lines.push(
            '',
            `@utility bg-gradient-${name} {`,
            `    background-image: var(--gradient-${name});`,
            '}',
        );
    }

    lines.push('');

    return lines.join('\n');
}

const fmt = (colour) =>
    `${css(colour)}${(colour.alpha ?? 1) < 1 ? ` / ${Math.round(colour.alpha * 100)}%` : ''}`;
const describe = (ref) =>
    typeof ref === 'string'
        ? ref
        : ref.mix
          ? `mix(${ref.mix[0]} ${ref.mix[1]}%, ${ref.mix[2]})`
          : `${ref.alpha[0]} at ${ref.alpha[1]}%`;

function report({
    config,
    families,
    analysis,
    flags,
    themes,
    gradients,
    pairResults,
    problems,
}) {
    const out = [
        '# Palette report',
        '',
        `${HEADER}`,
        '',
        'Standard: docs/standards/COLOR-DESIGN-SYSTEM.md.',
        '',
        '## Supplied colours',
        '',
    ];

    for (const item of analysis) {
        out.push(
            `- **${item.key}**${item.name ? ` (${item.name})` : ''}: ${item.hex} = ${css(item.colour)}; ${item.class.lightness}, ${item.class.chroma}, ${item.class.hue}, ${item.class.temperature}; anchor step ${item.anchor}.`,
            `  - White text on it ${item.white.toFixed(2)}:1, black text ${item.black.toFixed(2)}:1; as text on the light background ${item.onLight.toFixed(2)}:1, on the dark background ${item.onDark.toFixed(2)}:1.`,
        );
    }

    out.push('', '## Derived families', '');

    for (const family of Object.values(families).filter((f) => !f.exact)) {
        out.push(`- **${family.name}**: ${family.source}.`);
    }

    out.push('', '## Warnings', '');
    out.push(...(flags.length ? flags.map((f) => `- ${f}`) : ['- None.']));

    out.push('', '## Problems', '');
    out.push(
        ...(problems.length ? problems.map((p) => `- ${p}`) : ['- None.']),
    );

    for (const theme of Object.keys(THEME_SELECTORS)) {
        out.push('', `## Roles: ${theme}`, '');

        for (const [role, ref] of Object.entries(themes[theme].refs)) {
            const note = themes[theme].notes[role];

            out.push(
                `- \`${role}\`: ${describe(ref)} = ${fmt(themes[theme].values[role])}${note ? `. ${note}` : ''}`,
            );
        }

        for (const [name, g] of Object.entries(gradients[theme] ?? {})) {
            out.push(
                `- gradient \`${name}\`: weakest stop ${g.weakest.toFixed(2)}:1 with ${g.foreground}.`,
            );
        }

        out.push('', `### Declared pairs: ${theme}`, '');

        for (const pair of pairResults[theme]) {
            out.push(
                `- ${pair.ok ? 'PASS' : 'FAIL'} ${pair.ratio.toFixed(2)}:1 (min ${pair.min}) ${pair.fg} on ${pair.bg}${pair.over ? ` over ${pair.over}` : ''}`,
            );
        }
    }

    if (!(config.gradients ?? []).length) {
        out.push('', '## Gradients', '', '- None declared in palette.json.');
    }

    out.push('');

    return out.join('\n');
}

// ---------------------------------------------------------------- main

export function generate() {
    const config = readPalette();
    const flags = [];
    const problems = [];
    const families = {};
    const supplied = { ...config.colors, ...config.extra };
    const primary = hexToOklch(supplied.primary.hex);

    const add = (key, base, exact, source, constantChroma = false) => {
        families[key] = {
            ...buildFamily(key, base, exact, flags, constantChroma),
            exact,
            source,
            label: supplied[key]?.name ?? '',
        };
    };

    const derive = {
        secondary: () => ({
            l: 0.62,
            c: primary.c * 0.6,
            h: (primary.h + 330) % 360,
        }),
        accent: () => ({
            l: 0.62,
            c: Math.min(primary.c, 0.15),
            h: (primary.h + 150) % 360,
        }),
        neutral: () => ({ l: 0.62, c: 0.012, h: primary.h }),
        ...Object.fromEntries(
            Object.entries(DERIVED).map(([key, { h, c }]) => [
                key,
                () => ({ l: 0.62, c, h }),
            ]),
        ),
    };

    for (const key of [
        'primary',
        'secondary',
        'accent',
        'neutral',
        'success',
        'warning',
        'danger',
        'info',
    ]) {
        const hex = supplied[key]?.hex;

        if (hex) {
            add(
                key,
                hexToOklch(hex),
                true,
                `supplied ${hex.toUpperCase()}`,
                key === 'neutral',
            );
        } else {
            const base = derive[key]();

            add(
                key,
                base,
                false,
                `derived: hue ${base.h.toFixed(1)}, chroma ${base.c.toFixed(3)}`,
                key === 'neutral',
            );
        }
    }

    for (const [key, entry] of Object.entries(config.extra ?? {})) {
        add(
            key,
            hexToOklch(entry.hex),
            true,
            `supplied ${entry.hex.toUpperCase()}`,
        );
    }

    // §4: analysis and flags.
    const white = { l: 1, c: 0, h: 0 };
    const black = { l: 0, c: 0, h: 0 };
    const analysis = Object.entries(supplied)
        .filter(([, entry]) => entry?.hex)
        .map(([key, entry]) => {
            const colour = normalise(hexToOklch(entry.hex));

            return {
                key,
                name: entry.name,
                hex: entry.hex.toUpperCase(),
                colour,
                class: classify(colour),
                anchor: families[key].anchor,
                white: contrast(white, colour),
                black: contrast(black, colour),
                onLight: contrast(colour, families.neutral.steps[50]),
                onDark: contrast(colour, families.neutral.steps[950]),
            };
        });

    for (const item of analysis) {
        if (Math.max(item.white, item.black) < 4.5) {
            flags.push(
                `${item.key}: carries neither white nor black text at 4.5:1; large text, decoration and gradients only.`,
            );
        }

        for (const [status, hue] of Object.entries(STATUS_HUES)) {
            if (
                item.key !== status &&
                item.colour.c > 0.08 &&
                hueDistance(item.colour.h, hue) < 20
            ) {
                flags.push(
                    `${item.key}: hue within 20° of ${status}; status colours may be confused with it, so status never relies on colour alone.`,
                );
            }
        }
    }

    for (let i = 0; i < analysis.length; i += 1) {
        for (let j = i + 1; j < analysis.length; j += 1) {
            const [a, b] = [analysis[i], analysis[j]];

            if (deltaE(a.colour, b.colour) < 0.04) {
                flags.push(
                    `${a.key} and ${b.key} are near-duplicates (ΔE ${deltaE(a.colour, b.colour).toFixed(3)}).`,
                );
            }

            if (
                a.colour.c > 0.12 &&
                b.colour.c > 0.12 &&
                hueDistance(a.colour.h, b.colour.h) >= 150
            ) {
                flags.push(
                    `${a.key} and ${b.key} are vivid complements: never use one as text on the other.`,
                );
            }
        }
    }

    const themes = {};

    for (const theme of Object.keys(THEME_SELECTORS)) {
        themes[theme] = mapTheme(
            theme,
            families,
            config.roles?.[theme],
            problems,
        );
    }

    // A project role must exist in every theme, with a valid name.
    const roleSets = Object.entries(themes).map(([theme, mapped]) => [
        theme,
        Object.keys(mapped.refs).sort().join(' '),
    ]);

    for (const [theme, set] of roleSets.slice(1)) {
        if (set !== roleSets[0][1]) {
            problems.push(
                `the ${theme} theme does not define the same roles as ${roleSets[0][0]}; a project role belongs in every theme's "roles".`,
            );
        }
    }

    for (const role of Object.keys(themes.light.refs)) {
        if (!ROLE_NAMES.includes(role) && !/^[a-z][a-z0-9-]*$/.test(role)) {
            problems.push(
                `project role "${role}": lower-case letters, digits and dashes only.`,
            );
        }

        if (role.startsWith('palette-') || role.startsWith('color-')) {
            problems.push(
                `project role "${role}": must not start with palette- or color-.`,
            );
        }
    }

    const gradients = buildGradients(config, families, themes, problems);
    const components = parseBlock(
        existsSync(resolve(ROOT, PATHS.components))
            ? readFileSync(resolve(ROOT, PATHS.components), 'utf8')
            : '',
        ':root',
    );
    const pairs = readJson(PATHS.pairs);
    const pairResults = {};

    for (const theme of Object.keys(THEME_SELECTORS)) {
        try {
            const values = tokenValues(themes[theme].values, components);

            pairResults[theme] = checkPairs(pairs, values);
        } catch (error) {
            problems.push(`${theme}: ${error.message}`);
            pairResults[theme] = [];
        }

        for (const pair of pairResults[theme].filter((p) => !p.ok)) {
            problems.push(
                `${theme}: ${pair.fg} on ${pair.bg} is ${pair.ratio.toFixed(2)}:1, ${pair.min}:1 needed.`,
            );
        }
    }

    return {
        problems,
        files: {
            [PATHS.paletteCss]: paletteCss(families),
            [PATHS.themesCss]: themesCss(themes, gradients),
            [PATHS.prepaint]: prepaintView(themes),
            [PATHS.report]: report({
                config,
                families,
                analysis,
                flags,
                themes,
                gradients,
                pairResults,
                problems,
            }),
        },
    };
}

if (
    process.argv[1] &&
    resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
    const check = process.argv.includes('--check');
    const { problems, files } = generate();

    if (check) {
        const stale = Object.entries(files)
            .filter(([path, content]) => {
                const full = resolve(ROOT, path);

                return (
                    !existsSync(full) ||
                    readFileSync(full, 'utf8').replace(/\r\n/g, '\n') !==
                        content
                );
            })
            .map(([path]) => path);

        for (const path of stale) {
            console.error(
                `palette: ${path} is out of date; run \`npm run palette\`.`,
            );
        }

        for (const problem of problems) {
            console.error(`palette: ${problem}`);
        }

        process.exit(stale.length || problems.length ? 1 : 0);
    }

    writeFileSync(resolve(ROOT, PATHS.report), files[PATHS.report]);

    if (problems.length) {
        for (const problem of problems) {
            console.error(`palette: ${problem}`);
        }

        console.error(`palette: CSS not written; see ${PATHS.report}.`);
        process.exit(1);
    }

    writeFileSync(resolve(ROOT, PATHS.paletteCss), files[PATHS.paletteCss]);
    writeFileSync(resolve(ROOT, PATHS.themesCss), files[PATHS.themesCss]);
    mkdirSync(dirname(resolve(ROOT, PATHS.prepaint)), { recursive: true });
    writeFileSync(resolve(ROOT, PATHS.prepaint), files[PATHS.prepaint]);
    console.log(
        `palette: wrote ${PATHS.paletteCss}, ${PATHS.themesCss}, ${PATHS.prepaint}, ${PATHS.report}.`,
    );
}
